#!/usr/bin/env node
/**
 * Export NH Picks (lib/picks.mjs) from the AI reviewer's Supabase table to data/picks.json.
 *
 * Usage:
 *   node scripts/picks-export.mjs              # dry run: prints the counts and the picks, writes nothing
 *   node scripts/picks-export.mjs --write      # writes data/picks.json
 *   node scripts/picks-export.mjs --cutoff 4.6 --no-track-top
 *
 * Reads SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY from the environment or .env.local, the same
 * as scripts/judge-ingest.mjs. Read-only against Supabase; nothing on chain is touched.
 *
 * What reaches the file is listed in lib/picks.mjs: never peer comparisons or human-spice notes.
 */
import fs from 'node:fs';
import path from 'node:path';
import { DEFAULT_CUTOFF, selectPicks } from '../lib/picks.mjs';
import { readProjects } from '../lib/kv.mjs';

const ROOT = process.cwd();
const OUT = path.join(ROOT, 'data/picks.json');
const PAGE = 1000;
const COLUMNS = [
  'project_id',
  'name',
  'best_fit_track',
  'gate_pass',
  'weighted_score',
  'human_score_override',
  'scorecard',
  'near_primitives',
  'judge_memo',
].join(',');

function loadEnvLocal() {
  const envPath = path.join(ROOT, '.env.local');
  if (!fs.existsSync(envPath)) return;
  for (const line of fs.readFileSync(envPath, 'utf8').split('\n')) {
    const t = line.trim();
    if (!t || t.startsWith('#')) continue;
    const eq = t.indexOf('=');
    if (eq === -1) continue;
    const k = t.slice(0, eq).trim();
    if (k && !(k in process.env)) process.env[k] = t.slice(eq + 1).trim();
  }
}

function parseArgs(argv) {
  const args = { write: false, cutoff: DEFAULT_CUTOFF, perTrackTop: true };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--write') args.write = true;
    else if (argv[i] === '--no-track-top') args.perTrackTop = false;
    else if (argv[i] === '--cutoff' && argv[i + 1]) args.cutoff = Number(argv[++i]);
    else throw new Error(`Unknown argument: ${argv[i]}`);
  }
  if (!Number.isFinite(args.cutoff) || args.cutoff < 0 || args.cutoff > 5) throw new Error('--cutoff must be 0–5');
  return args;
}

/** Every row, paged so PostgREST's row cap cannot silently truncate the table. */
async function fetchAll(url, key) {
  const rows = [];
  for (let from = 0; ; from += PAGE) {
    const res = await fetch(`${url}/rest/v1/project_evaluations?select=${COLUMNS}&order=project_id`, {
      headers: { apikey: key, Authorization: `Bearer ${key}`, Range: `${from}-${from + PAGE - 1}`, 'Range-Unit': 'items' },
    });
    if (!res.ok && res.status !== 206) throw new Error(`Supabase read ${res.status}: ${await res.text()}`);
    const page = await res.json();
    rows.push(...page);
    if (page.length < PAGE) return rows;
  }
}

const readJson = (p) => JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8'));

async function main() {
  const args = parseArgs(process.argv.slice(2));
  loadEnvLocal();
  const url = process.env.SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) throw new Error('SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are required (env or .env.local)');

  const rows = await fetchAll(url, key);
  // Only projects with a live listing on chain, so every card's /p/{id} link resolves.
  const entries = await readProjects();
  const listed = new Set(
    entries.filter((e) => e.value !== null && e.value !== undefined).map((e) => String(e.key).replace(/^project\//, '')),
  );
  if (listed.size === 0) throw new Error('Read no project listings from chain; refusing to write an empty list');
  // Show each pick under its listing's name, the same as its /p/{id} page.
  const names = new Map(
    entries
      .filter((e) => typeof e.value?.name === 'string')
      .map((e) => [String(e.key).replace(/^project\//, ''), e.value.name]),
  );
  const unlisted = rows.filter((r) => r.gate_pass && !listed.has(r.project_id)).length;
  const picks = selectPicks(rows, {
    cutoff: args.cutoff,
    perTrackTop: args.perTrackTop,
    listed,
    names,
    hidden: readJson('data/hidden-projects.json'),
    duplicates: readJson('data/enrichment/duplicates.json'),
  });
  const file = {
    _note:
      'NH Picks: projects NEAR Hunt recommends, chosen from AI reviews of their repositories. Scores and memos are from NEAR Hunt\'s AI reviewer, not official hackathon judging. Sorted by track, then name. Generated by scripts/picks-export.mjs; selection rules in lib/picks.mjs.',
    generated_at: new Date().toISOString(),
    method: { cutoff: args.cutoff, per_track_top: args.perTrackTop },
    reviewed: rows.length,
    picks,
  };

  const tracks = new Set(picks.map((p) => p.track));
  console.log(`reviewed: ${rows.length}  passed gate: ${rows.filter((r) => r.gate_pass).length}  listings on chain: ${listed.size}  passed but not listed: ${unlisted}`);
  console.log(`picks: ${picks.length} across ${tracks.size} tracks (cutoff ${args.cutoff}, top of each track: ${args.perTrackTop ? 'yes' : 'no'})`);
  if (!args.write) {
    for (const p of picks) console.log(`  ${p.track.padEnd(28)} ${p.name}`);
    console.log('dry run: nothing written. Re-run with --write to update data/picks.json.');
    return;
  }
  fs.writeFileSync(OUT, `${JSON.stringify(file, null, 2)}\n`);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}

main().catch((e) => {
  console.error(e.message || e);
  process.exit(1);
});
